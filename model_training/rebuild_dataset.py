def main():
    print("=" * 50)
    print("学伴小管家 - 情绪训练数据集生成")
    print("=" * 50)

    # 统计各类别数据量
    total = 0
    for emotion, texts in data.items():
        count = len(texts)
        total += count
        print(f"  {emotion}: {count} 条")
    print(f"\n  总计: {total} 条")

    # 检查各类别是否满足最低要求
    requirements = {"crisis": 50, "depressed": 80, "anxious": 80, "stressed": 80, "happy": 80, "positive": 80, "neutral": 60}
    all_ok = True
    for emotion, req in requirements.items():
        actual = len(data[emotion])
        if actual < req:
            print(f"  [WARNING] {emotion} 只有 {actual} 条，需要至少 {req} 条")
            all_ok = False

    if all_ok:
        print("\n  [OK] 所有类别数量均满足要求")
    else:
        print("\n  [ERROR] 部分类别数量不足!")
        return

    # 去重检查
    all_texts = []
    for emotion, texts in data.items():
        for t in texts:
            if t in all_texts:
                print(f"  [WARNING] 重复数据: {t}")
            all_texts.append(t)

    if len(all_texts) != len(set(all_texts)):
        print(f"  [WARNING] 发现 {len(all_texts) - len(set(all_texts))} 条重复数据!")
    else:
        print(f"  [OK] 无重复数据")

    # 写入 CSV
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['text', 'emotion'])
        for emotion in ["crisis", "depressed", "anxious", "stressed", "happy", "positive", "neutral"]:
            for text in data[emotion]:
                writer.writerow([text, emotion])

    print(f"\n数据集已保存到: {OUTPUT_PATH}")
    print("=" * 50)
    print("生成完成!")

if __name__ == "__main__":
    main()
